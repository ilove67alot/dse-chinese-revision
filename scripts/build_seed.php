<?php
// Regenerates supabase/seed.sql from the JSON files in data/.
// Usage: php scripts/build_seed.php
declare(strict_types=1);

const WRITING_SOURCE_URL = 'https://learnsmart.edu.hk/blog/dse-%E4%B8%AD%E6%96%87%E4%BD%9C%E6%96%87%E9%A1%8C%E7%9B%AE';

$root = dirname(__DIR__);
$read = fn(string $path) => json_decode((string) file_get_contents("$root/data/$path"), true, 512, JSON_THROW_ON_ERROR);

function lit(mixed $value): string
{
    if ($value === null) {
        return 'null';
    }
    if (is_bool($value)) {
        return $value ? 'true' : 'false';
    }
    if (is_int($value)) {
        return (string) $value;
    }
    return "'" . str_replace("'", "''", (string) $value) . "'";
}

function jsonb(mixed $value): string
{
    return $value === null ? 'null' : lit(json_encode($value, JSON_UNESCAPED_UNICODE)) . '::jsonb';
}

function text_array(array $values): string
{
    return $values ? 'array[' . implode(', ', array_map('lit', $values)) . ']::text[]' : "'{}'::text[]";
}

function upsert(string $table, array $columns, array $rows): string
{
    $updates = implode(', ', array_map(fn($c) => "$c = excluded.$c", array_slice($columns, 1)));
    $sql = "insert into public.$table (" . implode(', ', $columns) . ") values\n";
    $sql .= implode(",\n", array_map(fn($r) => '  (' . implode(', ', $r) . ')', $rows));
    return $sql . "\non conflict ({$columns[0]}) do update set $updates;\n\n";
}

$fanwen = [];
foreach (glob("$root/data/fanwen/*.json") as $file) {
    $fanwen[] = json_decode((string) file_get_contents($file), true, 512, JSON_THROW_ON_ERROR);
}
usort($fanwen, fn($a, $b) => $a['sort_order'] <=> $b['sort_order']);

$out = "-- Generated by scripts/build_seed.php. Do not edit by hand; edit data/*.json and re-run.\n";
$out .= "-- Safe to run more than once: rows are inserted or updated by id.\n\nbegin;\n\n";

$out .= upsert('fanwen',
    ['code', 'sort_order', 'title', 'author', 'dynasty', 'source', 'genre', 'intro', 'sections', 'outline', 'theme', 'techniques', 'tips'],
    array_map(fn($f) => [
        lit($f['code']), lit($f['sort_order']), lit($f['title']), lit($f['author']), lit($f['dynasty']),
        lit($f['source']), lit($f['genre']), lit($f['intro']), jsonb($f['sections']), jsonb($f['outline']),
        lit($f['theme']), jsonb($f['techniques']), jsonb($f['tips']),
    ], $fanwen));

$out .= upsert('vocab',
    ['id', 'fanwen_code', 'piece', 'word', 'sentence', 'definition', 'pos', 'categories', 'tongjia', 'note'],
    array_map(fn($v) => [
        lit($v['id']), lit($v['fanwen_code']), lit($v['piece']), lit($v['word']), lit($v['sentence']),
        lit($v['definition']), lit($v['pos']), text_array($v['categories']), lit($v['tongjia']), lit($v['note']),
    ], $read('vocab.json')));

$out .= upsert('practice_questions',
    ['id', 'fanwen_code', 'sort_order', 'qtype', 'prompt', 'options', 'answer', 'explanation', 'marks'],
    array_map(fn($q) => [
        lit($q['id']), lit($q['fanwen_code']), lit($q['sort_order']), lit($q['qtype']), lit($q['prompt']),
        jsonb($q['options']), lit($q['answer']), lit($q['explanation'] ?: null), lit($q['marks']),
    ], $read('practice.json')));

$out .= upsert('writing_questions',
    ['id', 'year', 'paper', 'part', 'question_no', 'type', 'genre', 'prompt', 'has_material', 'has_image', 'source_url', 'verification'],
    array_map(fn($w) => [
        lit($w['id']), lit($w['year']), lit($w['paper']), lit($w['part']), lit($w['question_no']), lit($w['type']),
        lit($w['genre']), lit($w['prompt']), lit($w['has_material'] ?? false), lit($w['has_image'] ?? false),
        lit(WRITING_SOURCE_URL), lit($w['verification']),
    ], $read('writing.json')));

$out .= "commit;\n";
file_put_contents("$root/supabase/seed.sql", $out);
fwrite(STDERR, 'Wrote supabase/seed.sql (' . number_format(strlen($out)) . " bytes)\n");
